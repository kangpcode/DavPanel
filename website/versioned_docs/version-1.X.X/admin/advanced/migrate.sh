# Migrate

DavPanel is fully OS-agnostic, running smoothly on any Linux distribution. This makes migrating the panel along with all user data from one server to another easy and efficient.

Use **DavAdmin > Advanced > Migrate** to transfer all server data to a fresh DavPanel installation on a new server.

> ⚠️ This feature is intended only for full server migrations.

For detailed instructions, see the [Migrate DavAdmin to new server guide](https://davpanel.com/docs/articles/transfers/migrate-davadmin-to-new-server/)
